#!/usr/bin/env python3
"""Data check for BTC Pin Radar replay chunks (read-only).
Usage: python3 -I datacheck.py <datadir> <outfile>
"""
import sys, os, json, gzip, datetime, collections

D = sys.argv[1]
OUT = sys.argv[2]

def utc(ts):
    return datetime.datetime.fromtimestamp(ts, datetime.timezone.utc).strftime('%Y-%m-%d %H:%MZ')

chunks = sorted(f[:-7] for f in os.listdir(D) if f.endswith('.ndjson') and not f.endswith('.sum.ndjson') and not f.endswith('.loser.ndjson'))
lines = []
def P(*a):
    s = ' '.join(str(x) for x in a)
    lines.append(s); print(s)

fam_tickers = collections.defaultdict(dict)   # family -> ticker -> (chunk, closeTs, strike, official, truth)
fam_range = {}
chunk_info = {}
P('# DATA CHECK  (generated by scripts/datacheck.py)')
P('# data dir:', D)
P('')
P('%-8s %-7s %-6s %-17s %-17s %-7s %-7s %-7s %-8s %-6s %-7s %-7s %-7s %-7s %-8s %-6s %-5s %-5s %-6s' % (
  'chunk','mtime','nwin','first_closeTs','last_closeTs','ntick','dupTk','truthUP','dataUnrel','noFL','trows','ttk','tk!in','win!tr','tauMin','tauMax','frac','ord','gaps'))
all_states = collections.Counter(); all_sides = collections.Counter(); all_bk = collections.Counter()
for ch in chunks:
    fam = ch.split('_')[0]
    path = os.path.join(D, ch + '.ndjson')
    mtime = datetime.datetime.fromtimestamp(os.path.getmtime(path), datetime.timezone.utc).strftime('%H:%M')
    wins = []
    bad = 0
    with open(path) as f:
        for ln in f:
            ln = ln.strip()
            if not ln: continue
            try:
                wins.append(json.loads(ln))
            except Exception:
                bad += 1
    tks = [w['ticker'] for w in wins]
    cnt = collections.Counter(tks)
    dups = sum(1 for k, v in cnt.items() if v > 1)
    cts = [w['closeTs'] for w in wins]
    truth_up = sum(1 for w in wins if w.get('truth') == 'UP')
    du = sum(1 for w in wins if w.get('dataUnreliable'))
    nofl = sum(1 for w in wins if not w.get('firstLocked'))
    for w in wins:
        fam_tickers[fam].setdefault(w['ticker'], []).append((ch, w['closeTs'], w['strike'], w['official'], w['truth']))
    # trace
    tpath = os.path.join(D, ch + '.trace.ndjson.gz')
    trows = 0; ttk = set(); taus_min = None; taus_max = None; fracs = collections.Counter()
    order_ok = True; gaps = 0; tbad = 0
    last_tk = None; last_tau = None; seen_tk_blocks = collections.Counter()
    terr = None
    try:
        with gzip.open(tpath, 'rt') as f:
            for ln in f:
                try:
                    r = json.loads(ln)
                except Exception:
                    tbad += 1; continue
                trows += 1
                tk = r['tk']; tau = r['tau']
                ttk.add(tk)
                all_states[r.get('st')] += 1; all_sides[r.get('side')] += 1; all_bk[r.get('bk')] += 1
                fracs[round(tau - int(tau), 2)] += 1
                taus_min = tau if taus_min is None else min(taus_min, tau)
                taus_max = tau if taus_max is None else max(taus_max, tau)
                if tk != last_tk:
                    seen_tk_blocks[tk] += 1
                    last_tk = tk; last_tau = tau
                else:
                    if tau >= last_tau: order_ok = False
                    elif abs((last_tau - tau) - 1.0) > 1e-6: gaps += 1
                    last_tau = tau
    except Exception as e:
        terr = repr(e)
    multi_blocks = sum(1 for k, v in seen_tk_blocks.items() if v > 1)
    if multi_blocks: order_ok = False
    tk_not_in = len(ttk - set(tks))
    win_no_trace = len(set(tks) - ttk)
    P('%-8s %-7s %-6d %-17s %-17s %-7d %-7d %-7d %-8d %-6d %-7d %-7d %-7d %-7d %-8s %-6s %-5s %-5s %-6d' % (
        ch, mtime, len(wins), utc(min(cts)), utc(max(cts)), len(cnt), dups, truth_up, du, nofl, trows, len(ttk), tk_not_in, win_no_trace,
        taus_min, taus_max, ','.join(str(k) for k in sorted(fracs)), 'ok' if order_ok else 'BAD', gaps))
    if bad: P('  !! %d unparsable ndjson lines in %s' % (bad, ch))
    if tbad: P('  !! %d unparsable trace lines in %s' % (tbad, ch))
    if terr: P('  !! trace error in %s: %s' % (ch, terr))
    chunk_info[ch] = dict(fam=fam, n=len(wins), first=min(cts), last=max(cts))
    r = fam_range.get(fam)
    fam_range[fam] = (min(cts) if r is None else min(r[0], min(cts)), max(cts) if r is None else max(r[1], max(cts)))

P('')
P('Columns: nwin=windows in .ndjson; ntick=distinct tickers; dupTk=tickers repeated within chunk; truthUP=windows with truth UP;')
P('  dataUnrel=windows with dataUnreliable truthy; noFL=windows with firstLocked null; trows=trace rows; ttk=distinct tickers in trace;')
P('  tk!in=trace tickers absent from .ndjson; win!tr=.ndjson windows with no trace rows; frac=fractional parts of tau seen;')
P('  ord=rows contiguous per ticker and tau strictly decreasing; gaps=consecutive rows within a ticker whose tau step != 1 s.')
P('')
P('Trace state vocabulary:', dict(all_states))
P('Trace side vocabulary:', dict(all_sides))
P('Trace bk vocabulary:', dict(sorted(all_bk.items(), key=lambda kv: (kv[0] is None, kv[0]))))
P('')
for fam in sorted(fam_range):
    P('family %s: %d chunks, %d windows, %d distinct tickers, closeTs range %s .. %s' % (
        fam, sum(1 for c in chunk_info if chunk_info[c]['fam'] == fam), sum(chunk_info[c]['n'] for c in chunk_info if chunk_info[c]['fam'] == fam),
        len(fam_tickers[fam]), utc(fam_range[fam][0]), utc(fam_range[fam][1])))
    cross = sum(1 for k, v in fam_tickers[fam].items() if len(v) > 1)
    P('  tickers appearing in >1 chunk of the same family: %d' % cross)
    if cross:
        ex = [(k, [x[0] for x in v]) for k, v in fam_tickers[fam].items() if len(v) > 1][:5]
        P('  examples:', ex)
# overlap
fams = sorted(fam_tickers)
if len(fams) == 2:
    a, b = fams
    sa, sb = set(fam_tickers[a]), set(fam_tickers[b])
    both = sa & sb
    P('')
    P('tickers in both families: %d ; only %s: %d ; only %s: %d ; union: %d' % (len(both), a, len(sa - sb), b, len(sb - sa), len(sa | sb)))
    # agreement of market facts for shared tickers
    dis_close = dis_strike = dis_off = dis_truth = 0
    for tk in both:
        ra = fam_tickers[a][tk][0]; rb = fam_tickers[b][tk][0]
        if ra[1] != rb[1]: dis_close += 1
        if ra[2] != rb[2]: dis_strike += 1
        if ra[3] != rb[3]: dis_off += 1
        if ra[4] != rb[4]: dis_truth += 1
    P('shared tickers disagreeing between families on: closeTs=%d strike=%d official=%d truth=%d' % (dis_close, dis_strike, dis_off, dis_truth))
    # per-chunk coverage comparison
    P('')
    P('Per-chunk date coverage by family (first..last closeTs):')
    for fam in fams:
        for c in sorted(chunk_info):
            if chunk_info[c]['fam'] == fam:
                P('  %s  %s .. %s  (%d windows)' % (c, utc(chunk_info[c]['first']), utc(chunk_info[c]['last']), chunk_info[c]['n']))
    # only-in-one lists by date
    def daterange(tkset, fam):
        if not tkset: return 'none'
        cts = [fam_tickers[fam][t][0][1] for t in tkset]
        return '%s .. %s' % (utc(min(cts)), utc(max(cts)))
    P('')
    P('tickers only in %s: %d, closeTs range %s' % (a, len(sa - sb), daterange(sa - sb, a)))
    P('tickers only in %s: %d, closeTs range %s' % (b, len(sb - sa), daterange(sb - sa, b)))
    # monthly histogram of only-in-one
    def monthly(tkset, fam):
        c = collections.Counter()
        for t in tkset:
            ts = fam_tickers[fam][t][0][1]
            c[datetime.datetime.fromtimestamp(ts, datetime.timezone.utc).strftime('%Y-%m')] += 1
        return dict(sorted(c.items()))
    P('  by month, only-%s: %s' % (a, monthly(sa - sb, a)))
    P('  by month, only-%s: %s' % (b, monthly(sb - sa, b)))
    P('  by month, both: %s' % monthly(both, a))
with open(OUT, 'w') as f:
    f.write('\n'.join(lines) + '\n')
